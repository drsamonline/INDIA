#!/usr/bin/env python3
"""Build the INDIA monument site from data/monuments.json.

Generates:
  monuments/<id>.html      one page per monument module
  index.html               the landing page
  credits.html             sources, licences and image attributions

Usage:
  python3 tools/build_site.py            # build everything that exists
  python3 tools/build_site.py --only qutub-minar
"""
import hashlib, json, os, re, sys, html, argparse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def asset_version(*paths):
    """A short stamp of the files a page loads, so a cached module cannot
    outlive a deploy. GitHub Pages serves .js with a long cache and the
    filenames never change, which is how a browser ends up running last
    week's model against this week's HTML."""
    h = hashlib.md5()
    for p in paths:
        try:
            with open(os.path.join(ROOT, p), 'rb') as f:
                h.update(f.read())
        except OSError:
            pass
    return '?v=' + h.hexdigest()[:10]
DATA = os.path.join(ROOT, 'data', 'monuments.json')
TPL = os.path.join(ROOT, 'tools', 'templates')
SITE = 'https://drsamonline.github.io/INDIA/'

def esc(s):
    return html.escape(str(s), quote=True)

def page_data(m):
    keys = ('name', 'deva', 'place', 'state', 'era', 'period', 'style', 'unesco',
            'wikipedia', 'history', 'facts', 'links', 'image',
            'fidelity', 'contributors')   # the honesty block and its credits
    d = {k: m.get(k) for k in keys}
    return json.dumps(d, ensure_ascii=False)

def build_pages(monuments, only=None):
    tpl = open(os.path.join(TPL, 'monument.html')).read()
    made = []
    for m in monuments:
        if only and m['id'] != only:
            continue
        mod = os.path.join(ROOT, 'assets', 'js', 'monuments', m['id'] + '.js')
        if not os.path.exists(mod):
            print('  skip (no module):', m['id'])
            continue
        out = tpl
        ver = asset_version('assets/js/monument-engine.js', 'assets/js/monuments/%s.js' % m['id'],
                            'assets/css/monument.css', 'assets/js/index-data.js')
        repl = {
            '__V__': ver,
            '__NAME__': esc(m['name']), '__BLURB__': esc(m['blurb']),
            '__PLACE__': esc(m['place']), '__STATE__': esc(m['state']),
            '__THEME__': m.get('accent', '#e8c39a'), '__WIKI__': esc(m['wikipedia']),
            '__ID__': m['id'], '__OGIMAGE__': m['image']['src'], '__DATA__': page_data(m),
        }
        for k, v in repl.items():
            out = out.replace(k, v)
        path = os.path.join(ROOT, 'monuments', m['id'] + '.html')
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'w').write(out)
        made.append(path)
        print('  page:', os.path.relpath(path, ROOT))
    return made

def build_nav_index(monuments):
    items = [{'id': m['id'], 'name': m['name'], 'place': m['place'], 'deva': m['deva']} for m in monuments]
    path = os.path.join(ROOT, 'assets', 'js', 'index-data.js')
    with open(path, 'w') as f:
        f.write('/* generated by tools/build_site.py — the order of the atlas */\n')
        f.write('window.INDIA_INDEX = ' + json.dumps(items, ensure_ascii=False) + ';\n')
    print('  data: assets/js/index-data.js')

def build_index(monuments):
    tpl_path = os.path.join(TPL, 'index.html')
    if not os.path.exists(tpl_path):
        return
    tpl = open(tpl_path).read()
    cards = []
    for i, m in enumerate(monuments, 1):
        stem = os.path.basename(m['image']['src']).replace('.jpg', '')
        tag = ''
        if m.get('unesco') and m['unesco'] != '—':
            label = 'UNESCO' if 'World Heritage Site' in m['unesco'] else 'UNESCO tentative'
            tag = f'<span class="card-tag">{label}</span>'
        cards.append(f"""
      <a class="card" href="monuments/{m['id']}.html" data-region="{esc(m['region'])}" data-id="{m['id']}">
        <div class="card-media">
          <picture>
            <source type="image/webp" srcset="assets/img/thumb/{stem}-450.webp 450w, assets/img/thumb/{stem}-900.webp 900w" sizes="(max-width: 720px) 92vw, (max-width: 1000px) 46vw, 31vw">
            <img src="assets/img/thumb/{stem}-900.jpg" srcset="assets/img/thumb/{stem}-450.jpg 450w, assets/img/thumb/{stem}-900.jpg 900w" sizes="(max-width: 720px) 92vw, (max-width: 1000px) 46vw, 31vw" alt="{esc(m['name'])}, {esc(m['place'])}" loading="lazy" width="900" height="600">
          </picture>
          <span class="card-num">{i:02d}</span>{tag}
        </div>
        <div class="card-body">
          <p class="card-kicker">{esc(m['place'])} · {esc(m['state'])}</p>
          <h3 class="card-title">{esc(m['name'])} <span class="deva">{esc(m['deva'])}</span></h3>
          <p class="card-meta">{esc(m['era'])}</p>
          <p class="card-blurb">{esc(m['blurb'])}</p>
          <span class="card-go">Enter the miniature <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h14M13 6l6 6-6 6"/></svg></span>
        </div>
      </a>""")
    out = tpl.replace('<!--CARDS-->', ''.join(cards))
    years = sorted([(m.get('year', 0), m['name'], m['place'], m['id']) for m in monuments])
    tl = []
    for yr, name, place, mid in years:
        label = f"{abs(yr)} BCE" if yr < 0 else str(yr)
        tl.append(f'      <a class="tl-item" href="monuments/{mid}.html"><span class="tl-year">{label}</span>'
                  f'<span class="tl-name">{esc(name)}</span><span class="tl-place">{esc(place)}</span></a>')
    out = out.replace('<!--TIMELINE-->', '\n'.join(tl))
    words = {12: 'Twelve', 13: 'Thirteen', 14: 'Fourteen', 15: 'Fifteen', 16: 'Sixteen', 17: 'Seventeen',
             18: 'Eighteen', 19: 'Nineteen', 20: 'Twenty', 21: 'Twenty-one', 22: 'Twenty-two', 23: 'Twenty-three',
             24: 'Twenty-four'}
    out = out.replace('__COUNTWORDL__', words.get(len(monuments), str(len(monuments))).lower())
    out = out.replace('__COUNTWORD__', words.get(len(monuments), str(len(monuments))))
    out = out.replace('__STATES__', str(len({m['state'] for m in monuments})))
    out = out.replace('__COUNT__', str(len(monuments)))
    out = out.replace('__FIRSTNAME__', esc(monuments[0]['name']))
    out = out.replace('__FIRSTID__', monuments[0]['id'])
    out = out.replace('__FIRSTIMG__', monuments[0]['image']['src'])
    out = out.replace('__V__', asset_version('assets/css/site.css', 'assets/js/site.js'))
    out = out.replace('__FIRSTWEBP__', monuments[0]['image']['src'].replace('.jpg', '.webp'))
    out = out.replace('__OLDESTNAME__', years[0][1])
    out = out.replace('__NEWESTNAME__', years[-1][1])
    out = out.replace('__OLDEST__', f"{years[0][1]} · {abs(years[0][0])} BCE" if years[0][0] < 0 else f"{years[0][1]} · {years[0][0]}")
    out = out.replace('__NEWEST__', f"{years[-1][1]} · {years[-1][0]}")
    open(os.path.join(ROOT, 'index.html'), 'w').write(out)
    print('  page: index.html')

def build_credits(monuments):
    tpl_path = os.path.join(TPL, 'credits.html')
    if not os.path.exists(tpl_path):
        return
    tpl = open(tpl_path).read()
    rows = []
    for m in monuments:
        im = m['image']
        lic = im.get('license', '')
        licurl = im.get('licenseUrl') or '#'
        rows.append(f"""      <tr>
        <td><a href="monuments/{m['id']}.html">{esc(m['name'])}</a><br><span class="muted">{esc(m['place'])}</span></td>
        <td>{esc(im.get('artist', 'Unknown'))}</td>
        <td><a href="{esc(licurl)}" rel="noopener" target="_blank">{esc(lic)}</a></td>
        <td><a href="{esc(im.get('page', '#'))}" rel="noopener" target="_blank">Commons file</a></td>
      </tr>""")
    fidrows = []
    for m in monuments:
        f = m.get('fidelity') or {}
        people = [c for c in (m.get('contributors') or []) if c.get('name')]
        who = ', '.join(
            f'<a href="{esc(c["url"])}" target="_blank" rel="noopener">{esc(c["name"])}</a>'
            if c.get('url') else esc(c['name']) for c in people) or '<span class="muted">—</span>'
        fidrows.append(f"""      <tr>
        <td><a href="monuments/{m['id']}.html">{esc(m['name'])}</a></td>
        <td><span class="fid-pill fid-{esc(f.get('level', 'approximate'))}">{esc(f.get('level', 'approximate'))}</span></td>
        <td>{esc(f.get('note', ''))}</td>
        <td>{who}</td>
      </tr>""")
    out = tpl.replace('<!--FIDROWS-->', '\n'.join(fidrows))
    out = out.replace('<!--ROWS-->', '\n'.join(rows))
    words = {12: 'Twelve', 13: 'Thirteen', 14: 'Fourteen', 15: 'Fifteen', 16: 'Sixteen', 17: 'Seventeen',
             18: 'Eighteen', 19: 'Nineteen', 20: 'Twenty', 21: 'Twenty-one', 22: 'Twenty-two', 23: 'Twenty-three',
             24: 'Twenty-four'}
    out = out.replace('__COUNTWORDL__', words.get(len(monuments), str(len(monuments))).lower())
    out = out.replace('__COUNTWORD__', words.get(len(monuments), str(len(monuments))))
    out = out.replace('__STATES__', str(len({m['state'] for m in monuments})))
    out = out.replace('__COUNT__', str(len(monuments)))
    open(os.path.join(ROOT, 'credits.html'), 'w').write(out)
    print('  page: credits.html')

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only')
    args = ap.parse_args()
    monuments = json.load(open(DATA))
    print('building', len(monuments), 'monuments')
    build_pages(monuments, args.only)
    build_nav_index(monuments)
    if not args.only:
        build_index(monuments)
        build_credits(monuments)

if __name__ == '__main__':
    main()
